test('real korean CSV XLSX and CP949 files clean, merge, and export',async()=>{
  const csvName='고객_2026년11월.csv';
  const [csv]=await readFile(new File([readFileSync(`public/samples/${csvName}`)],csvName));
  assert.deepEqual(csv.headers,['고객명','이메일','거래일','금액','메모']);
  assert.deepEqual(csv.mapping,['이름','이메일','날짜','금액','메모']);
  assert.equal(csv.rowNumbers?.[0],3);
  assert.equal(csv.rows.length,7);
  const suggested=applySuggestions(settingsDefault(),[csv]);
  assert.deepEqual(suggested.dateColumns,['날짜']);
  assert.deepEqual(suggested.moneyColumns,['금액']);
  const workbook=await readFile(new File([readFileSync('public/samples/주문_추가.xlsx')],'주문_추가.xlsx'));
  assert.equal(workbook.length,1);
  const sheet=workbook[0];
  assert.equal(sheet.sheet,'주문');
  assert.deepEqual(sheet.mapping,['ID','이름','이메일','날짜','금액']);
  assert.equal(parseDate(sheet.rows[0][3],'ISO'),'2026-11-06');
  assert.equal(excelSerial(2026,11,6),sheet.rows[0][3]);
  const [cp949]=await readFile(new File([readFileSync('public/samples/거래처_cp949.csv')],'거래처_cp949.csv'));
  assert.deepEqual(cp949.mapping,['이름','날짜','금액']);
  assert.equal(cp949.rows[0][0],'홍길동');
  const merged=transform([csv,sheet],{...settingsDefault(),dedup:true,keys:['이메일'],dateColumns:['날짜'],moneyColumns:['금액']});
  assert.equal(merged.inputCount,10);
  assert.equal(merged.removed,2);
  assert.equal(merged.rows.length,8);
  assert.equal(merged.rows[0]['금액'],1200000);
  assert.equal(merged.rows[0]['날짜'],'2026-11-02');
  assert.equal(merged.rows[1]['금액'],850000);
  assert.equal(merged.rows[4]['날짜'],'2026.02.31');
  assert.equal(merged.rows[4]['금액'],'금액없음');
  assert.equal(merged.rows[5]['금액'],15000);
  assert.equal(merged.summary.dateConverted,6);
  assert.equal(merged.summary.dateKept,2);
  assert.equal(merged.summary.moneyConverted,6);
  assert.equal(merged.summary.moneyKept,2);
  assert.equal(merged.issues.length,3);
  const book=XLSX.read(exportWorkbook(merged,{...settingsDefault(),dedup:true,keys:['이메일'],dateColumns:['날짜'],moneyColumns:['금액']}),{type:'array',cellNF:true});
  assert.equal(book.Sheets['정리 결과'].D2.v,1200000);
  assert.equal(book.Sheets['정리 결과'].D2.z,'#,##0');
  assert.equal(book.Sheets['정리 결과'].C2.v,'2026-11-02');
  assert.equal(book.Sheets['정리 요약'].B2.v,10);
  assert.ok(book.Sheets['검토 사항']);
  const cp949Result=transform([cp949],{...settingsDefault(),dateColumns:['날짜'],moneyColumns:['금액']});
  assert.equal(cp949Result.rows[0]['날짜'],'2026-11-02');
  assert.equal(cp949Result.rows[0]['금액'],1200000);
  assert.equal(cp949Result.rows[1]['날짜'],'2026-11-08');
});
