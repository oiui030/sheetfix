test('korean dates, won amounts, and ambiguous order',()=>{
  assert.equal(parseDate('2026.11.02','ISO'),'2026-11-02');
  assert.equal(parseDate('2026. 11. 02','ISO'),'2026-11-02');
  assert.equal(parseDate('２０２６．１１．０２','ISO'),'2026-11-02');
  assert.equal(parseDate('2026년 11월 2일','ISO'),'2026-11-02');
  assert.equal(parseDate('2026년 11월 2일 월요일','ISO'),'2026-11-02');
  assert.equal(parseDate('2026년 11월 2일 14:30','ISO'),'2026-11-02');
  assert.equal(parseDate('20261102','ISO'),'2026-11-02');
  assert.equal(parseDate(20261102,'ISO'),'2026-11-02');
  assert.equal(parseDate('2026.02.31','ISO'),null);
  assert.equal(parseDate('11/13/2026','ISO'),null);
  assert.equal(parseDate('11/13/2026','MDY'),'2026-11-13');
  assert.equal(parseMoney('1,200,000원'),1200000);
  assert.equal(parseMoney('1，200，000원'),1200000);
  assert.equal(parseMoney('￦15,000'),15000);
  assert.equal(parseMoney('-₩1,200,000'),-1200000);
  assert.equal(parseMoney('₩-1,200'),-1200);
  assert.equal(parseMoney('(35,000원)'),-35000);
  assert.equal(parseMoney('금액없음'),null);
  assert.equal(parseMoney('1.234,56'),null);
});
